
def addition(num_1,num_2):
    add = num_1 + num_2
    print(f"Addition of {num_1} and {num_2} is {add}")

def subtraction(num_1,num_2):
    sub = num_1 - num_2
    print("Subtraction:",sub)

def multiplication(num_1,num_2):
    mul = num_1 * num_2
    print("Multiplication:",mul)

def division(num_1,num_2):
    div = num_1 / num_2
    print("Division:",div)