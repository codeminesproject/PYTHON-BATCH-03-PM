
"""

Membership operator:
It is used to check values exist or not in collection datatype such as list,set,tuple,dictionary

Type:

in
not int

"""

list_var = [89,76,45,11,67,89,76,89]

print("values of list:",list_var)

print("check 23 in list:",23 in list_var)
print("check 11 in list:",11 in list_var)

print("------------------------------------------------------------")

print("check 23 not in list:",23 not in list_var)
print("check 11 not in list:",11 not in list_var)