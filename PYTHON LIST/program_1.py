
"""
List is a data type which allows us to store more than one value in single variable

Syntax:

variable_name = [value_1, value_2, value_3,......]

"""

list_var = [89,76,45,11,67,89,76,89]

print("values of list:",list_var)
print("datatype of list:",type(list_var))

